    H.svg(mk('span', 'disc', r, { 'aria-hidden': 'true' }), '', REPLAY, { viewBox: '0 0 24 24' });
    el.replayTxt = mk('span', 'txt', r);
    r.addEventListener('click', function () { if (endOpts && endOpts.onReplay) endOpts.onReplay(); });
