    H.svg(brand, 'jdisc', JDISC, { viewBox: '0 0 112 112' });
    H.text(mk('div', 'wordmark', brand), 'JUNE');
    el.tagline = mk('div', 'tagline', e, { 'data-ui': 'tagline' });
